/**
 * Validates whether an input represents a valid [longitude, latitude] GeoJSON coordinate pair.
 * Longitude must be between -180 and +180 degrees.
 * Latitude must be between -90 and +90 degrees.
 *
 * @param {any} coordinates - Expects [longitude, latitude]
 * @returns {boolean}
 */
function isValidCoordinate(coordinates) {
	if (!Array.isArray(coordinates) || coordinates.length !== 2) {
		return false
	}

	const [lng, lat] = coordinates

	if (typeof lng !== 'number' || typeof lat !== 'number') {
		return false
	}

	if (isNaN(lng) || isNaN(lat)) {
		return false
	}

	if (lng < -180 || lng > 180) {
		return false
	}

	if (lat < -90 || lat > 90) {
		return false
	}

	return true
}

/**
 * Normalizes varied coordinate inputs into a standard [longitude, latitude] array.
 * Accepts:
 * - [lng, lat]
 * - { longitude, latitude }
 * - { lng, lat }
 * - { lon, lat }
 *
 * @param {Array|Object} input
 * @returns {[number, number]|null} [longitude, latitude] or null if invalid
 */
function normalizeCoordinates(input) {
	if (!input) return null

	// Case 1: Array format [longitude, latitude]
	if (Array.isArray(input) && input.length === 2) {
		const lng = Number(input[0])
		const lat = Number(input[1])
		if (isValidCoordinate([lng, lat])) {
			return [lng, lat]
		}
		return null
	}

	// Case 2: Object format { latitude, longitude } or { lat, lng } or { lat, lon }
	if (typeof input === 'object' && input !== null) {
		const lngVal = input.longitude !== undefined ? input.longitude : (input.lng !== undefined ? input.lng : input.lon)
		const latVal = input.latitude !== undefined ? input.latitude : input.lat

		if (lngVal !== undefined && latVal !== undefined) {
			const lng = Number(lngVal)
			const lat = Number(latVal)
			if (isValidCoordinate([lng, lat])) {
				return [lng, lat]
			}
		}
	}

	return null
}

/**
 * Privacy Shield: Fuzzes a precise coordinate pair by adding random Gaussian/uniform jitter
 * within a bounded radius (default: 500m to 1000m).
 *
 * DISCOVERY-ONLY GUARANTEE:
 * Approximate coordinates generated by fuzzLocation are strictly intended for coarse,
 * privacy-preserving proximity discovery (radius clustering).
 * They MUST NEVER be treated as verified donor locations, proof of presence, or the
 * basis for final clinical eligibility or dispatch decisions.
 *
 * @param {[number, number]} coordinates - [longitude, latitude]
 * @param {number} radiusMeters - Maximum jitter radius in meters (default 750m)
 * @returns {[number, number]} [fuzzedLongitude, fuzzedLatitude]
 */
function fuzzLocation(coordinates, radiusMeters = 750) {
	if (!isValidCoordinate(coordinates)) {
		throw new Error('Cannot fuzz invalid coordinates.')
	}

	const [lng, lat] = coordinates

	// Random distance with uniform area distribution: r = sqrt(random) * radiusMeters
	const r = Math.sqrt(Math.random()) * radiusMeters
	// Random direction in radians: 0 to 2*PI
	const theta = Math.random() * 2 * Math.PI

	// Earth constants:
	// 1 degree of latitude ~= 111,320 meters
	// 1 degree of longitude ~= 111,320 * cos(latitude in radians) meters
	const latRad = (lat * Math.PI) / 180
	const cosLat = Math.cos(latRad)

	// Avoid division by zero at extreme poles (|lat| >= 89.9 deg)
	const safeCosLat = Math.abs(cosLat) < 0.0001 ? 0.0001 : cosLat

	const deltaLat = (r * Math.cos(theta)) / 111320
	const deltaLng = (r * Math.sin(theta)) / (111320 * safeCosLat)

	let fuzzedLat = lat + deltaLat
	let fuzzedLng = lng + deltaLng

	// Clamp to legitimate bounds
	fuzzedLat = Math.max(-90, Math.min(90, fuzzedLat))
	fuzzedLng = Math.max(-180, Math.min(180, fuzzedLng))

	// Round to 5 decimal places (~1.1 meter precision post-fuzz)
	return [
		Math.round(fuzzedLng * 100000) / 100000,
		Math.round(fuzzedLat * 100000) / 100000,
	]
}

/**
 * Calculates the great-circle distance between two [longitude, latitude] points in kilometers
 * using the standard Haversine formula.
 *
 * @param {[number, number]} coord1 - [longitude, latitude] of point 1
 * @param {[number, number]} coord2 - [longitude, latitude] of point 2
 * @returns {number} Distance in kilometers (rounded to 2 decimal places)
 */
function calculateHaversineDistanceKm(coord1, coord2) {
	if (!isValidCoordinate(coord1) || !isValidCoordinate(coord2)) {
		throw new Error('Both points must be valid [longitude, latitude] coordinate pairs.')
	}

	const [lon1, lat1] = coord1
	const [lon2, lat2] = coord2

	const R = 6371 // Earth radius in kilometers

	const dLat = ((lat2 - lat1) * Math.PI) / 180
	const dLon = ((lon2 - lon1) * Math.PI) / 180

	const lat1Rad = (lat1 * Math.PI) / 180
	const lat2Rad = (lat2 * Math.PI) / 180

	const a =
		Math.sin(dLat / 2) * Math.sin(dLat / 2) +
		Math.cos(lat1Rad) * Math.cos(lat2Rad) * Math.sin(dLon / 2) * Math.sin(dLon / 2)

	const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a))
	const distance = R * c

	return Math.round(distance * 100) / 100
}

/**
 * Privacy Shield: Sanitizes donor profile objects for external/discovery payloads,
 * guaranteeing that precise or approximate coordinates, push keys, and PII are never leaked.
 *
 * @param {Object} donorProfile - Raw Mongoose document or plain object
 * @returns {Object} Publicly safe summary
 */
function sanitizeDonorForDiscovery(donorProfile) {
	if (!donorProfile) return null

	const raw = typeof donorProfile.toObject === 'function' ? donorProfile.toObject() : { ...donorProfile }

	return {
		profileId: raw._id,
		bloodGroup: raw.bloodGroup,
		state: raw.state,
		city: raw.city,
		maxTravelDistanceKm: raw.maxTravelDistanceKm || 15,
		availabilityStatus: raw.availabilityStatus || 'Ready',
		clinicalEligibilityStatus: raw.clinicalEligibilityStatus || 'Pending_Clinical_Evaluation',
		isEmergencyDonor: Boolean(raw.isEmergencyDonor),
		hasLocation: Boolean(raw.location && raw.location.coordinates),
	}
}

